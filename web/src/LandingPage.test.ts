import { fireEvent } from "@testing-library/dom";
import { expect, it, vi } from "vitest";
import html from "../index.html?raw";

it("works offline with four real routes, keyboard panels and an honest local form", () => {
  vi.useFakeTimers();
  vi.stubGlobal("matchMedia", (query: string) => ({ matches: query.includes("reduce"), addEventListener() {} }));
  vi.stubGlobal("scrollTo", vi.fn());
  const page = new DOMParser().parseFromString(html, "text/html");
  expect(page.querySelectorAll(".view")).toHaveLength(4);
  expect(page.querySelectorAll("img,video,script[type=module]")).toHaveLength(0);
  expect(page.querySelector('a[href="#"]')).toBeNull();
  document.body.innerHTML = page.body.innerHTML;
  history.replaceState({}, "", "#/unknown");
  window.eval(Array.from(page.querySelectorAll("script")).find((script) => !script.src)!.textContent!);
  expect(location.hash).toBe("#/home");
  const active = () => document.querySelectorAll(".view.is-active");
  expect(active()).toHaveLength(1);
  fireEvent.click(document.querySelector('.nav [data-route="capabilities"]')!);
  expect(active()[0]).toHaveAttribute("id", "view-capabilities");
  const panels = document.querySelectorAll(".panel");
  fireEvent.keyDown(panels[0], { key: "ArrowRight" });
  expect(panels[1]).toHaveAttribute("aria-selected", "true");
  fireEvent.click(document.querySelector('.nav [data-route="evidence"]')!);
  expect(active()[0]).toHaveAttribute("id", "view-evidence");
  expect(document.querySelector('.stat-card[data-to="26"] b')).toHaveTextContent("26");
  fireEvent.click(document.querySelector('.nav [data-route="about"]')!);
  const form = document.querySelector("#view-about form") as HTMLFormElement;
  fireEvent.submit(form);
  expect(form.parentElement).toHaveTextContent("请先填写邮箱");
  const email = form.querySelector("input")!;
  fireEvent.input(email, { target: { value: "demo@example.org" } });
  fireEvent.submit(form);
  vi.advanceTimersByTime(600);
  expect(JSON.parse(localStorage.getItem("xingmu-lead")!).email).toBe("demo@example.org");
  expect(form.parentElement).toHaveTextContent("尚未发送给项目团队");
  expect(active()).toHaveLength(1);
  vi.useRealTimers(); vi.unstubAllGlobals();
});
